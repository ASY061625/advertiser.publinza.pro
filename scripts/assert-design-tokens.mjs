#!/usr/bin/env node
/**
 * Fails the build when a source file uses a design-system colour utility that
 * Tailwind did not actually generate.
 *
 * Tailwind silently ignores an unknown class in JSX — rename a token and every
 * `bg-surface-card` still in the tree becomes a no-op that renders an unstyled
 * surface with no warning anywhere. This checks the classes we wrote against
 * the CSS that was really emitted, so a rename cannot land half-finished.
 *
 * Only our own token namespaces are checked, so `text-sm`, `border-b` and
 * arbitrary values like `bg-[linear-gradient(...)]` are never candidates.
 */
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const ROOTS = [
    'brand', 'ink', 'canvas', 'card', 'sunken', 'surface', 'teal', 'gold',
    'success', 'warning', 'danger', 'info', 'status', 'overlay', 'row-hover',
    'subtle', 'strong',
];

const PREFIXES = ['bg', 'text', 'border', 'ring', 'fill', 'stroke', 'divide', 'outline', 'from', 'via', 'to'];

const pattern = new RegExp(`\\b(${PREFIXES.join('|')})-((?:${ROOTS.join('|')})(?:-[a-z0-9]+)*)\\b`, 'g');

// --- Collect the emitted CSS -------------------------------------------------
const assetDir = 'public/build/assets';
let css = '';
try {
    for (const file of readdirSync(assetDir)) {
        if (file.endsWith('.css')) css += readFileSync(path.join(assetDir, file), 'utf8');
    }
} catch {
    console.error(`✗ No built CSS in ${assetDir}. Run \`npm run build\` first.`);
    process.exit(1);
}

if (css === '') {
    console.error(`✗ No CSS files found in ${assetDir}.`);
    process.exit(1);
}

// --- Collect the classes we wrote -------------------------------------------
function walk(dir) {
    const out = [];

    for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) out.push(...walk(full));
        else if (/\.(tsx?|blade\.php)$/.test(entry.name)) out.push(full);
    }

    return out;
}

const files = [...walk('resources/js'), ...walk('resources/views')];

const used = new Map(); // class -> Set of files

for (const file of files) {
    const source = readFileSync(file, 'utf8');

    for (const [, prefix, name] of source.matchAll(pattern)) {
        const cls = `${prefix}-${name}`;
        if (!used.has(cls)) used.set(cls, new Set());
        used.get(cls).add(file);
    }
}

// --- Compare -----------------------------------------------------------------
const missing = [];

for (const [cls, where] of used) {
    // A variant renders the class as `.hover\:bg-brand-hover:hover`, so the
    // class is not always preceded by a dot. Guard both ends against a longer
    // identifier instead, so `bg-brand` cannot match `bg-brand-hover`.
    const escaped = cls.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (!new RegExp(`(?<![\\w-])${escaped}(?![\\w-])`).test(css)) {
        missing.push({ cls, where: [...where] });
    }
}

if (missing.length > 0) {
    console.error('✗ These design-system classes are used but were never generated by Tailwind:\n');
    for (const { cls, where } of missing) {
        console.error(`  ${cls}`);
        for (const file of where) console.error(`      ${file}`);
    }
    console.error('\nThey render as no-ops. Fix the class name or add the token to tailwind.config.ts.');
    process.exit(1);
}

console.log(`✓ all ${used.size} design-system colour classes resolve`);
